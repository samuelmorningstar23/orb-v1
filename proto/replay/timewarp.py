"""Time-warped ghost: t_cf(S) = t_actual(S) + Delta(S), inverted to s(t), with the pit-lane switch (roadmap v5 task 0.5).

Inputs: a DriverTrajectory (actual world), the track and pit lane, and a CounterfactualLaps table (Workstream 2's per-lap
deltas: lap, lap_delta, cumulative_delta, pit_state, optional quantile columns or whole-curve samples; or a FIXTURE).

Ghost schedule, lap by lap (D_k = T_k + delta_k, so cumulative deltas are exact at every lap boundary):
    follow      the ghost keeps the actual lap's own time-distance shape, scaled to D_k: the delta is spread uniformly in
                lap-time fraction (a constant relative pace offset within the lap). This is the SAFE version; a tyre-demand
                weighted spread (more of the delta in the high-load sectors) is documented as future work in PERF.md.
    reference   an actual stop the counterfactual does not make: the ghost flies past on the driver's median clean-lap profile
    pit pair    a counterfactual stop the actual did not make: on-track parts on the reference profile, the pit lane on the
                driver's own recorded transit (time-shifted; the event median when the driver has no normal stop), the on-track
                time scaled so D_p + D_{p+1} is honoured exactly (kappa reported; a kappa far from 1 means the deltas do not
                carry the pit loss)
    same-lap stop in both worlds: follow, the ghost also uses the pit lane
Quantiles: whole-curve samples when present (each sample warps the whole race, then per-frame quantiles of position), else
the q10/q90 lap-delta columns as two curves. q10/q90 name the ELAPSED-DELTA quantiles (Workstream 2's convention: negative =
faster), so S_cf_q10 >= S_cf_median >= S_cf_q90 along the track; ordering is enforced and violations counted.
Frames at 1 Hz: t, s_actual, s_cf_median, s_cf_q10, s_cf_q90 (+ unwrapped S), laps, compounds, tyre ages, time_delta_s
(gap at the actual car's position, positive = ghost behind), distance_delta_m (positive = ghost ahead), pit flags and
pit-lane progress, track status; compressed float32 with a sha256 sidecar.
"""
