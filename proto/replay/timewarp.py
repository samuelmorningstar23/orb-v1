def stints_to_lap_map(stints: list[dict], n_laps: int) -> tuple[dict[int, str], dict[int, int]]:
    """{lap: compound}, {lap: tyre_age} from [{compound, first_lap, last_lap}] (age 1 on the first lap of a stint)."""
    comp, age = {}, {}
    for st in stints:
        for k in range(int(st['first_lap']), int(st['last_lap']) + 1):
            comp[k] = str(st['compound']).upper(); age[k] = k - int(st['first_lap']) + 1
    last_c = comp.get(max(comp) if comp else 1, 'UNKNOWN'); last_first = max((int(s['first_lap']) for s in stints), default=1)
    for k in range(1, n_laps + 1):
        if k not in comp:
            comp[k] = last_c; age[k] = k - last_first + 1
    return comp, age


def plan_to_stints(plan: dict) -> list[dict]:
    """Lock-style plan {stints: [{compound, laps}], pit_laps} -> [{compound, first_lap, last_lap}]."""
    out, k = [], 1
    for st in plan['stints']:
        n = int(st['laps'])
        out.append(dict(compound=str(st['compound']).upper(), first_lap=k, last_lap=k + n - 1))
        k += n
    return out


def stints_from_trajectory(traj: DriverTrajectory) -> tuple[list[dict], list[int]]:
    """Actual stints and in-laps from the recorded lap table."""
    lt = traj.laps
    stints = []
    for st, g in lt.groupby('stint', sort=True):
        stints.append(dict(compound=str(g['compound'].iloc[0]).upper(), first_lap=int(g['lap'].min()), last_lap=int(g['lap'].max())))
    pit_laps = [int(x) for x in lt.loc[lt['pit_in'].astype(bool), 'lap']]
    return stints, pit_laps


@dataclass
class CounterfactualLaps:
    lap: np.ndarray
    lap_delta: np.ndarray
    cumulative_delta: np.ndarray
    pit_state: list[str]
    actual_pit_laps: list[int]
    cf_pit_laps: list[int]
    actual_stints: list[dict]
    cf_stints: list[dict]
    lap_delta_q10: Optional[np.ndarray] = None
    lap_delta_q90: Optional[np.ndarray] = None
    samples: Optional[np.ndarray] = None          # (n_samples, n_laps) whole-curve lap deltas
    source: str = 'workstream2'
    label: str = ''
    scenario_id: str = ''
    meta: dict = field(default_factory=dict)

    @property
    def n_laps(self) -> int:
        return int(self.lap.max()) if len(self.lap) else 0

    def delta_map(self, which: str = 'median') -> dict[int, float]:
        arr = {'median': self.lap_delta, 'q10': self.lap_delta_q10, 'q90': self.lap_delta_q90}[which]
        if arr is None:
            arr = self.lap_delta
        return {int(k): float(v) for k, v in zip(self.lap, arr)}

    def is_identity(self) -> bool:
        return bool(np.allclose(self.lap_delta, 0.0) and sorted(self.actual_pit_laps) == sorted(self.cf_pit_laps))

    def to_dict(self) -> dict:
        return dict(scenario_id=self.scenario_id, source=self.source, label=self.label, lap=self.lap.astype(int).tolist(), lap_delta=np.round(self.lap_delta, 4).tolist(),
                    cumulative_delta=np.round(self.cumulative_delta, 4).tolist(), pit_state=list(self.pit_state), actual_pit_laps=list(self.actual_pit_laps), cf_pit_laps=list(self.cf_pit_laps),
                    actual_stints=self.actual_stints, cf_stints=self.cf_stints, lap_delta_q10=None if self.lap_delta_q10 is None else np.round(self.lap_delta_q10, 4).tolist(),
                    lap_delta_q90=None if self.lap_delta_q90 is None else np.round(self.lap_delta_q90, 4).tolist(), n_samples=0 if self.samples is None else int(len(self.samples)), meta=self.meta)


def from_table(table, actual_plan: dict | list[dict], cf_plan: dict | list[dict], scenario_id: str = '', source: str = 'workstream2', label: str = '', n_laps: Optional[int] = None,
               samples: Optional[np.ndarray] = None, actual_pit_laps: Optional[list[int]] = None, cf_pit_laps: Optional[list[int]] = None) -> CounterfactualLaps:
    """Workstream 2's laps table (DataFrame / list of records / dict of columns with lap, lap_delta, cumulative_delta, pit_state and
    optional lap_delta_q10 / lap_delta_q90 or cumulative_delta_q10 / cumulative_delta_q90) plus the two plans (lock-style
    {stints, pit_laps} or [{compound, first_lap, last_lap}])."""
    df = pd.DataFrame(table)
    if 'lap' not in df.columns:
        raise ValueError('laps table needs a lap column')
    df = df.sort_values('lap').reset_index(drop=True)
    lap = df['lap'].to_numpy(dtype=int)
    if 'lap_delta' in df.columns:
        ld = df['lap_delta'].to_numpy(dtype=float)
    elif 'delta_s' in df.columns:                                        # fixtures/sidecars/cf_*_lap_deltas.json records
        ld = df['delta_s'].to_numpy(dtype=float)
    elif 'cumulative_delta' in df.columns:
        ld = np.diff(np.concatenate([[0.0], df['cumulative_delta'].to_numpy(dtype=float)]))
    else:
        raise ValueError('laps table needs lap_delta (or delta_s / cumulative_delta)')
    ld = np.nan_to_num(ld, nan=0.0)
    cum = df['cumulative_delta'].to_numpy(dtype=float) if 'cumulative_delta' in df.columns else np.cumsum(ld)
    pit_state = [str(x) for x in df['pit_state']] if 'pit_state' in df.columns else ['none'] * len(df)
    q10 = q90 = None
    # the halo needs the whole-curve quantiles of the CUMULATIVE delta (Workstream 2 samples whole curves); per-lap increment
    # quantiles summed over laps over-state the spread, so they are only the fallback
    if 'cumulative_delta_q10' in df.columns and 'cumulative_delta_q90' in df.columns:
        q10 = np.diff(np.concatenate([[0.0], np.nan_to_num(df['cumulative_delta_q10'].to_numpy(dtype=float))])); q90 = np.diff(np.concatenate([[0.0], np.nan_to_num(df['cumulative_delta_q90'].to_numpy(dtype=float))]))
    elif 'lap_delta_q10' in df.columns and 'lap_delta_q90' in df.columns:
        q10 = np.nan_to_num(df['lap_delta_q10'].to_numpy(dtype=float)); q90 = np.nan_to_num(df['lap_delta_q90'].to_numpy(dtype=float))
    n = int(n_laps or lap.max())
    a_st = plan_to_stints(actual_plan) if isinstance(actual_plan, dict) else list(actual_plan)
    c_st = plan_to_stints(cf_plan) if isinstance(cf_plan, dict) else list(cf_plan)
    a_pits = list(actual_plan.get('pit_laps', [])) if isinstance(actual_plan, dict) else (actual_pit_laps if actual_pit_laps is not None else [s['last_lap'] for s in a_st[:-1]])
    c_pits = list(cf_plan.get('pit_laps', [])) if isinstance(cf_plan, dict) else (cf_pit_laps if cf_pit_laps is not None else [s['last_lap'] for s in c_st[:-1]])
    # pit_state may also name the counterfactual in-laps
    named = [int(k) for k, st in zip(lap, pit_state) if st.lower() in ('in', 'in_lap', 'pit_in', 'stop', 'box')]
    if named and not c_pits:
        c_pits = named
    return CounterfactualLaps(lap=lap, lap_delta=ld, cumulative_delta=cum, pit_state=pit_state, actual_pit_laps=[int(x) for x in a_pits], cf_pit_laps=[int(x) for x in c_pits],
                              actual_stints=a_st, cf_stints=c_st, lap_delta_q10=q10, lap_delta_q90=q90, samples=None if samples is None else np.asarray(samples, dtype=float),
                              source=source, label=label, scenario_id=scenario_id, meta=dict(n_laps=n))


def identity_laps(traj: DriverTrajectory, label: str = 'identity: counterfactual plan == actual plan, zero deltas') -> CounterfactualLaps:
    stints, pits = stints_from_trajectory(traj)
    n = traj.n_laps
    lap = np.arange(1, n + 1)
    return CounterfactualLaps(lap=lap, lap_delta=np.zeros(n), cumulative_delta=np.zeros(n), pit_state=['none'] * n, actual_pit_laps=pits, cf_pit_laps=list(pits), actual_stints=stints, cf_stints=list(stints),
                              source='identity', label=label, scenario_id='identity', meta=dict(n_laps=n))


def fixture_laps(traj: DriverTrajectory, intervention_lap: int, to_compound: str, seed: int = 2026, n_samples: int = 200, pit_loss_s: float = PIT_LOSS_FIXTURE_S,
                 scenario_id: str = '') -> CounterfactualLaps:
    """FIXTURE counterfactual: the recorded plan up to intervention_lap - 1, a stop on intervention_lap, to_compound to the flag.
    Synthetic deltas from a toy pace model (compound offset + linear degradation + pit loss + warm-up); whole-curve samples from
    seeded perturbations of the degradation rates and the pit loss. Labelled FIXTURE everywhere it is displayed."""
    rng = np.random.default_rng(seed)
    n = traj.n_laps
    a_st, a_pits = stints_from_trajectory(traj)
    p = int(np.clip(intervention_lap, 1, n - 1))
    c_st = []
    for st in a_st:
        if st['last_lap'] < p:
            c_st.append(dict(st))
        elif st['first_lap'] <= p:
            c_st.append(dict(compound=st['compound'], first_lap=st['first_lap'], last_lap=p))
    if not c_st:
        c_st = [dict(compound=a_st[0]['compound'], first_lap=1, last_lap=p)]
    c_st.append(dict(compound=str(to_compound).upper(), first_lap=p + 1, last_lap=n))
    c_pits = [pl for pl in a_pits if pl < p] + [p]
    a_comp, a_age = stints_to_lap_map(a_st, n); c_comp, c_age = stints_to_lap_map(c_st, n)
    deg = dict(SOFT=0.060, MEDIUM=0.035, HARD=0.020, INTERMEDIATE=0.05, WET=0.05, UNKNOWN=0.035)
    offset = dict(SOFT=0.0, MEDIUM=0.30, HARD=0.60, INTERMEDIATE=2.0, WET=4.0, UNKNOWN=0.3)
    laps = np.arange(1, n + 1)
    added = sorted(set(c_pits) - set(a_pits)); removed = sorted(set(a_pits) - set(c_pits))

    def curve(deg_mult: dict[str, float], pit_loss: float) -> np.ndarray:
        d = np.zeros(n)
        for k in laps:
            ca, cc = a_comp[k], c_comp[k]
            pace_a = offset[ca] + deg[ca] * deg_mult[ca] * a_age[k]
            pace_c = offset[cc] + deg[cc] * deg_mult[cc] * c_age[k]
            d[k - 1] = pace_c - pace_a
            if k in added:
                d[k - 1] += 0.6 * pit_loss
            if k - 1 in added:
                d[k - 1] += 0.4 * pit_loss + 0.4
            if k in removed:
                d[k - 1] -= 0.6 * pit_loss
            if k - 1 in removed:
                d[k - 1] -= 0.4 * pit_loss + 0.4
        return d
    base_mult = {c: 1.0 for c in deg}
    median_curve = curve(base_mult, pit_loss_s)
    samples = np.empty((n_samples, n))
    for i in range(n_samples):
        mult = {c: float(np.exp(rng.normal(0.0, 0.25))) for c in deg}
        samples[i] = curve(mult, float(rng.normal(pit_loss_s, 1.5)))
    cum_s = np.cumsum(samples, axis=1)
    q10c = np.quantile(cum_s, 0.1, axis=0); q90c = np.quantile(cum_s, 0.9, axis=0)
    q10 = np.diff(np.concatenate([[0.0], q10c])); q90 = np.diff(np.concatenate([[0.0], q90c]))
    pit_state = ['in' if k in c_pits else ('out' if k - 1 in c_pits else 'none') for k in laps]
    sid = scenario_id or f'FIXTURE_{traj.event}_{traj.driver}_stop{p}_{str(to_compound).upper()}'
    return CounterfactualLaps(lap=laps, lap_delta=median_curve, cumulative_delta=np.cumsum(median_curve), pit_state=pit_state, actual_pit_laps=a_pits, cf_pit_laps=c_pits, actual_stints=a_st, cf_stints=c_st,
                              lap_delta_q10=q10, lap_delta_q90=q90, samples=samples, source='FIXTURE', label=FIXTURE_LABEL, scenario_id=sid,
                              meta=dict(n_laps=n, intervention_lap=p, to_compound=str(to_compound).upper(), seed=seed, n_samples=n_samples, pit_loss_s=pit_loss_s, toy_model=dict(deg=deg, offset=offset)))


